/**
 * Seeds a LOCAL development backend with a test account and one in-progress
 * trip, so the companion app has something to sign in to and show.
 *
 *   node scripts/dev-seed.mjs [http://localhost:5000/api]
 *
 * Credentials are generated on first run and kept in `.env.test.local`
 * (git-ignored). The script refuses to talk to anything but a loopback host.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const api = (process.argv[2] ?? 'http://localhost:5000/api').replace(/\/$/, '');
const host = new URL(api).hostname;
if (!['localhost', '127.0.0.1', '[::1]'].includes(host)) {
  throw new Error(`Refusing to seed a non-local server: ${host}`);
}

const envPath = join(dirname(fileURLToPath(import.meta.url)), '..', '.env.test.local');
if (!existsSync(envPath)) {
  writeFileSync(
    envPath,
    [
      '# Local test account for the companion app. Generated by scripts/dev-seed.mjs.',
      'TEST_USERNAME=mobiletester',
      'TEST_EMAIL=mobiletester@example.test',
      `TEST_PASSWORD=${randomBytes(12).toString('base64url')}`,
      '',
    ].join('\n')
  );
}
const env = Object.fromEntries(
  readFileSync(envPath, 'utf8')
    .split('\n')
    .filter((line) => line && !line.startsWith('#'))
    .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1).trim()])
);

let token = null;

async function call(method, path, body) {
  const response = await fetch(`${api}${path}`, {
    method,
    headers: {
      'content-type': 'application/json',
      'x-client-platform': 'mobile',
      ...(token ? { authorization: `Bearer ${token}` } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const json = await response.json().catch(() => ({}));
  if (!response.ok) {
    const error = new Error(`${method} ${path} -> ${response.status} ${JSON.stringify(json).slice(0, 400)}`);
    error.status = response.status;
    throw error;
  }
  return json.data;
}

const credentials = { email: env.TEST_EMAIL, password: env.TEST_PASSWORD };
let auth;
try {
  auth = await call('POST', '/auth/login', credentials);
  console.log('signed in as existing test user');
} catch {
  auth = await call('POST', '/auth/register', { username: env.TEST_USERNAME, ...credentials });
  console.log('registered test user');
}
token = auth.accessToken;
console.log('refresh token in body:', typeof auth.refreshToken === 'string');

const trips = await call('GET', '/trips');
const existing = (Array.isArray(trips) ? trips : (trips?.trips ?? [])).find(
  (trip) => trip.title === 'Emulator Test Trip'
);
if (existing) {
  console.log('trip already seeded:', existing.id);
  process.exit(0);
}

const day = (offset) => new Date(Date.now() + offset * 86_400_000).toISOString().slice(0, 10);
const at = (offset, hour) => `${day(offset)}T${String(hour).padStart(2, '0')}:00:00.000Z`;

const trip = await call('POST', '/trips', {
  title: 'Emulator Test Trip',
  startDate: day(-1),
  endDate: day(3),
  timezone: 'America/New_York',
  status: 'In Progress',
});
console.log('trip', trip.id);

const location = await call('POST', '/locations', {
  tripId: trip.id,
  name: 'Grand Central Terminal',
  latitude: 40.7527,
  longitude: -73.9772,
});
console.log('location', location.id);

for (const [name, offset, hour] of [
  ['Coffee near the station', 0, 14],
  ['Museum visit', 0, 19],
  ['Harbor walk', 1, 15],
]) {
  const activity = await call('POST', '/activities', {
    tripId: trip.id,
    name,
    startTime: at(offset, hour),
    endTime: at(offset, hour + 1),
    timezone: 'America/New_York',
  });
  console.log('activity', activity.id, name);
}
